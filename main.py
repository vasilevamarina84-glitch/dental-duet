knowledge_base = {
    "привет": "Здравствуйте! Чем могу помочь?",
    "здравствуйте": "Добрый день! Я виртуальный помощник стоматологии.",
    "цена": "Стоимость зависит от услуги. Например: чистка зубов — от 3000 ₽, лечение кариеса — от 5000 ₽.",
    "стоимость": "Стоимость зависит от услуги. Например: чистка зубов — от 3000 ₽, лечение кариеса — от 5000 ₽.",
    "запись": "Чтобы записаться на приём, напишите 'записаться' и ваше имя. Например: 'записаться Анна'",
    "записаться": "Отлично! Я записал вас. Наш администратор свяжется с вами в ближайшее время.",
    "график": "Мы работаем с 9:00 до 21:00, без выходных.",
    "режим работы": "Мы работаем с 9:00 до 21:00, без выходных.",
    "адрес": "Мы находимся по адресу: ул. Пушкина, д. 10, офис 5.",
    "спасибо": "Пожалуйста! Всегда рада помочь 😊",
    "пока": "До свидания! Будьте здоровы!",
}
# ============================================
# ФУНКЦИЯ ПОИСКА ОТВЕТА
# ============================================

def get_answer(user_input):
    """
    Функция ищет ключевое слово в сообщении пользователя
    и возвращает соответствующий ответ.
    Если ключевое слово не найдено — возвращает стандартный ответ.
    """
    user_input = user_input.lower()  # Переводим всё в нижний регистр (чтобы "Привет" и "привет" работали одинаково)

    # Перебираем все ключевые слова из базы знаний
    for keyword in knowledge_base:
        if keyword in user_input:  # Если ключевое слово есть в сообщении пользователя
            return knowledge_base[keyword]  # Возвращаем соответствующий ответ

    # Если ни одно ключевое слово не найдено
    return "Я пока не знаю ответа на этот вопрос. Но я учусь! Можете переформулировать."

# ============================================
# ЗАПУСК ЧАТ-БОТА
# ============================================

print("=" * 50)
print("🦷 Добро пожаловать в чат-бот стоматологии 'Дентал-Профи'!")
print("Задайте мне вопрос или напишите 'пока' для выхода.")
print("=" * 50)

while True:
    # 1. Спрашиваем у пользователя
    user_input = input("\nВы: ")

    # 2. Проверяем, не хочет ли пользователь выйти
    if user_input.lower() == "пока":
        print("Бот: До свидания! Будьте здоровы!")
        break  # Выходим из цикла (завершаем программу)

    # 3. Получаем ответ от бота
    bot_answer = get_answer(user_input)

    # 4. Выводим ответ
    print("Бот:", bot_answer)